export type MeetingLanguage = (typeof meetingLanguages)[number];
const names = new Intl.DisplayNames(["en"], { type: "language" });
export const meetingLanguageNames = Object.fromEntries(
  meetingLanguages.map((code) => [code, names.of(code) ?? code]),
) as Record<MeetingLanguage, string>;
export function geminiCode(code: MeetingLanguage) {
  return code === "en-IN"
    ? "en"
    : code === "te-IN"
      ? "te"
      : code === "hi-IN"
        ? "hi"
        : code;
}
